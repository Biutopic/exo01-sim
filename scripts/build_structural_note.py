"""Generate docs/STRUCTURAL.md: the design-load note (descente de charges) for the coupling.

    python scripts/build_structural_note.py

Reads results/coupling/connection_loads.json and writes the note with every number computed, so nothing in the
document is typed by hand. Re-run it after any change to the loads.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = json.loads((ROOT / "results" / "coupling" / "connection_loads.json").read_text())

SURGE_ONLY = {"moored", "fwd100", "rev50", "rev70", "rev100", "estop"}
YAW_CASES = {"diff_one", "diff_opp"}

G_DYN = 2.5      # snatch allowance on the characteristic load. JUDGEMENT: the time-domain peaks do not converge
                 # (COUPLING.md section 14), so this is mooring practice (2-3x on quasi-static), not a computed value.
F_TEXTILE = 5.0  # required minimum breaking load / design load, for rope and webbing in cyclic marine service
F_METAL = 4.0    # required WLL basis / design load, for shackles, padeyes and bolted connections

ARR = "I_fwd_midship_crossed"
a = D["arrangements"][ARR]


def characteristic(e):
    """Larger of the static envelope and the linear wave peak."""
    st = abs(float(e["max_abs_T_N"]))
    wv = float(e["wave_peak_N"] or 0.0)
    return max(st, wv), ("static " + str(e["governing_case"]) if st >= wv else "wave")


rows = []
for eid, e in sorted(a["elements"].items(), key=lambda kv: -max(abs(kv[1]["max_abs_T_N"]),
                                                               kv[1]["wave_peak_N"] or 0)):
    ch, src = characteristic(e)
    if ch < 1.0:
        rows.append(dict(id=eid, kind=e["kind"], L=e["length_m"], ch=0.0, src="never loaded",
                         design=0.0, mbl=0.0, daf=e["dynamic_amplification"]))
        continue
    des = G_DYN * ch
    rows.append(dict(id=eid, kind=e["kind"], L=e["length_m"], ch=ch, src=src, design=des,
                     mbl=(F_TEXTILE if e["kind"] in ("line", "bridle") else F_METAL) * des,
                     daf=e["dynamic_amplification"]))

pts = [p for p in a["attachment_points"] if p["max_resultant_N"] >= 1.0]


def fmt(x, n=0):
    return f"{x:,.{n}f}".replace(",", " ")


L = []
w = L.append
w("# EXO-01 coupling — note de calcul : descente de charges et liaisons")
w("")
w("**Phase 1 of 2. This is a load note, not a structural verification.** It resolves every coupling connection into")
w("a design force with a direction, sizes the connection hardware, and specifies what each attachment must be able")
w("to carry. It does **not** verify a single member, because the project holds no frame sections, no material")
w("specification and no laminate schedule — `config missing_inputs` already records that gap. Phase 2 (member and")
w("laminate verification) needs the inputs listed in §7 and cannot be done from what exists today.")
w("")
w(f"Generated by `scripts/build_structural_note.py` from `results/coupling/connection_loads.json` "
  f"({D['generated']}). Every figure is computed; none is typed in.")
w("")
w("## 1. Scope, and one defect that limits it")
w("")
w("The loads come from the coupled two-body static solver (nine thrust-derived load cases) and the linear")
w("frequency-domain response in the three Erdre reference waves. Two limits matter more than anything else here:")
w("")
w("1. **The time-domain snatch load is not bounded by the model.** §14 showed the tension-only peaks wander between")
w("   11,0 and 15,7 kN across time steps, with no element damping anywhere in the model. So the dynamic allowance")
w(f"   below (×{G_DYN:g}) is **engineering judgement from mooring practice, not a computed number.** Measuring a real")
w("   snatch load is the single change that would most reduce the uncertainty in this note.")
w("2. **A known equilibrium defect quarantines the two differential-thrust cases.** A fender with a declared contact")
w("   axis applies a spurious couple of cross(a−b, f) — measured at 178 N·m from one bumper at 2 652 N. The")
w("   surge-only cases are unaffected (force residual 0,02 N, moment residual 0,0–1,8 N·m). The yaw cases")
w("   `diff_one` and `diff_opp` carry a 0,5 % error in this arrangement and up to 7,6 % in the brief's own")
w("   configuration. The couple is **restoring**, so modelled yaw is too small and any preload set by a yaw case is")
w(f"   **underestimated** — non-conservative. See COUPLING.md §16. Loads below that are governed by a yaw case are")
w("   marked; treat them as lower bounds.")
w("")
w("## 2. Design basis")
w("")
w("| | value | basis |")
w("|---|---|---|")
w("| Characteristic load F_k | larger of the static envelope and the linear wave peak | computed |")
w(f"| Dynamic allowance γ_dyn | ×{G_DYN:g} | JUDGEMENT — mooring practice; the snatch load is not bounded (§1.1) |")
w(f"| Design load F_d | γ_dyn × F_k | |")
w(f"| Textile elements | MBL ≥ {F_TEXTILE:g} × F_d | rope and webbing, cyclic marine service with UV and chafe |")
w(f"| Metallic fittings | WLL basis ≥ {F_METAL:g} × F_d | shackles, padeyes, bolted connections |")
w("")
w("Arrangement studied: **" + a["title"] + "**, at the §15 design preload of "
  f"{fmt(a['primary_preload_N'])} N per primary element, secondaries rigged snug at {fmt(a['snug_preload_N'])} N.")
w("")
w("## 3. Element design loads")
w("")
w("| element | type | length | F_k | governed by | DAF (linear) | F_d | required capacity |")
w("|---|---|---|---|---|---|---|---|")
for r in rows:
    if r["ch"] < 1.0:
        w(f"| `{r['id']}` | {r['kind']} | {r['L']:.2f} m | — | {r['src']} | — | — | "
          f"insurance only; size for handling, not load |")
        continue
    cap = (f"MBL ≥ **{fmt(r['mbl'])} N**" if r["kind"] in ("line", "bridle")
           else f"WLL basis ≥ **{fmt(r['mbl'])} N**")
    mark = " ⚠" if str(r["src"]).replace("static ", "") in YAW_CASES else ""
    w(f"| `{r['id']}` | {r['kind']} | {r['L']:.2f} m | {fmt(r['ch'])} N | {r['src']}{mark} | "
      f"{r['daf'] if r['daf'] is not None else '—'} | {fmt(r['design'])} N | {cap} |")
w("")
w("⚠ = governed by a quarantined yaw case; treat as a lower bound (§1.2).")
w("")
w("**The two crossed stern ropes are the ones to watch.** Their static load is small but their linear dynamic")
w("amplification is **4,2–4,5**, an order above every other element: the wave governs them, not the statics. They")
w("must be the softest and longest elements in the arrangement, or they will be the ones that snatch.")
w("")
w("## 4. Attachment points")
w("")
w("Resultant per lug, in the body's own frame, with the unit direction of the force **on that body**. At these")
w("displacements (≤ 37 mm, ≤ 0,5°) body and world axes coincide to better than the precision that matters.")
w("")
w("| side | point (m) | elements | max resultant | direction | governing case |")
w("|---|---|---|---|---|---|")
for p in pts:
    mark = " ⚠" if p["governing_case"] in YAW_CASES else ""
    w(f"| {p['side']} | {p['point']} | {', '.join(f'`{e}`' for e in p['elements'])} | "
      f"{fmt(p['max_resultant_N'])} N | {p['direction']} | {p['governing_case']}{mark} |")
w("")
w("## 5. Connections — how to make each one")
w("")
w("The absolute loads are small: nothing exceeds about 800 N characteristic. **Strength is not the design driver —")
w("fatigue, chafe, pull-out and stiffness are.** Everything below follows from that.")
w("")
w("### 5.1 Boat side — the critical unknown")
w("")
w("Every boat-side load lands on an existing cleat, and **no cleat on Hydronaute has a known rating.** A design load")
w(f"of {fmt(max(r['design'] for r in rows if r['ch'] >= 1))} N is trivial for a through-bolted cleat on a backing")
w("plate and entirely capable of tearing out a cleat that is screwed into a thin deck laminate. This is the one")
w("item that must be resolved before any trial.")
w("")
w("- **Verify or refit every cleat used**: through-bolted, stainless fasteners, with a backing plate or load-")
w("  spreading pad under the deck, not screws into the laminate. Pull-out, not shear, is the failure mode.")
w("- **Orient for the actual direction.** The midship spring pulls at roughly `[0.87, 0.49, 0.08]` — nearly")
w("  horizontal and about 30° off fore-and-aft. A cleat handles that; a padeye must be set in that plane or it")
w("  bends.")
w("- **Soft shackles or spliced eyes, not S-hooks**, on anything that cycles. An open hook on the element whose")
w("  failure loses reverse restraint is the wrong terminal.")
w("- **Chafe protection where the crossed ropes cross the deck edge.** They lie across the aft deck by geometry")
w("  (§15.1), which is ordinary practice but needs a rubbing strip or a lead.")
w("")
w("### 5.2 EXO side")
w("")
w("- **Rear bumper mounts** at `[2.10, ±0.90, 0.25]`: pure fore-and-aft compression, direction `[-1, 0, 0]`. Load")
w("  the crossmember in line; avoid a cantilevered pad bracket, which turns an axial load into a bending moment at")
w("  the weld.")
w("- **Forward posts** at `[4.95, ±2.25, 0.30]` and **mid posts** at `[2.10, ±2.25, 0.30]`: these take rope loads")
w("  at an angle, so the lug must be a padeye in the load plane with a gusset into the post, not a tab welded to a")
w("  tube wall. A tube loaded by a surface-welded tab fails by wall tearing well below the tab's own rating.")
w("- **Dockwheel brackets**: carry **0 N in every static case** in this arrangement. Size them as a physical stop")
w("  and for handling. §15.4 also found the 30 mm gap is not a dimension needing precision.")
w("")
w("### 5.3 Hardware that matches these loads")
w("")
w(f"Against the largest textile design load of {fmt(max((r['design'] for r in rows if r['kind'] in ('line','bridle') and r['ch']>=1), default=0))} N:")
w("")
w("- **12 mm polyester double braid** (MBL typically 25–30 kN) — comfortably inside the 5:1 requirement, and §14")
w("  already chose it over the 4,8 mm UHMWPE on stiffness grounds. Stay with it.")
w("- **A 2\" (50 mm) retractable ratchet strap** (MBL 13,5 kN, WLL 4,5 kN) also satisfies 5:1 for the springs and")
w("  the crossed ropes, which makes it a legitimate choice for those two pairs — with an inline dynamometer, because")
w("  §5–§7 showed rope tension is what sets the rear compression exactly, and a ratchet handle reads nothing. Treat")
w("  the webbing as an annually replaced consumable: its rating is a land-cargo rating, not a marine cyclic one.")
w("- **Shackles**: any 8–10 mm stainless bow shackle clears the 4:1 metallic requirement at these loads. Size by")
w("  the pin and eye geometry, not by rating.")
w("")
w("## 6. Contact and bearing")
w("")
w("| contact | load | note |")
w("|---|---|---|")
w("| rear bumpers | ~800 N over a pad of order 200 × 200 mm → **≈ 0,2 bar** | far below anything that marks a hull |")
w("| dockwheels | 0 N in this arrangement | stop only |")
w("| bow saddle (arrangement C only) | 0,41 bar over 120 × 400 mm (§12) | versus 9,9 bar for a bare rope — the saddle is what makes a bow lead acceptable |")
w("| under-hull sling (sandwich option) | 1,7–3,4 bar on a 2\" strap; 0,29–0,57 bar on a 300 mm sling | if ever used, lifting slings, not tie-downs |")
w("")
w("## 7. What phase 2 needs, and what would change these numbers")
w("")
w("**Required before any member or laminate check:**")
w("")
w("1. EXO frame drawings: section sizes, wall thicknesses, material and temper, and the joint details at every")
w("   attachment point above.")
w("2. Hydronaute's deck laminate schedule and the construction of each cleat mounting, or a pull test on one.")
w("3. The float-to-frame connection — the model assumes the floats and frame move as one rigid body and")
w("   `missing_inputs` flags the stiffness as unknown.")
w("")
w("**Would materially change the loads in this note:**")
w("")
w("4. **The pods' bollard thrust.** §15.5 found `diff_opp` binds the preload of thirteen of seventeen arrangements,")
w("   and it rests on a 1 500 N order-of-magnitude guess. Measure it and every preload in this note tightens.")
w("5. **A measured snatch load**, which would replace the ×2,5 judgement with a number.")
w("6. **The three contact stiffnesses** (bumper, wheel, rope), still unmeasured, which spread the quasi-static")
w("   answer by a factor of 3 (§7) even though rope tension pins it exactly.")
w("7. **The fender-couple defect** (§1.2), which must be fixed before the yaw-governed loads can be trusted.")
w("")
w("---")
w("")
w("*Exploratory. Assumed geometry, masses, contact stiffnesses and boat attachment points. This note is the load")
w("input a structural office needs; it is not a verification, and it carries no sign-off.*")

(ROOT / "docs" / "STRUCTURAL.md").write_text("\n".join(L) + "\n")
print(f"written docs/STRUCTURAL.md ({len('\n'.join(L).splitlines())} lines)")
print(f"largest textile design load: "
      f"{max((r['design'] for r in rows if r['kind'] in ('line','bridle') and r['ch']>=1), default=0):.0f} N")
